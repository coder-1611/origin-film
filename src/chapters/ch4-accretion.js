// IV · ACCRETION (58.000 → 81.988 s, bars 18–28)
// Showcase: a Three.js scene graph with a custom post chain: depth-texture bokeh DOF (gather
// for surfaces, energy-conserving scatter bokeh for point emitters), heavy bloom and grain.
//
//   glare (III hand-off) → pull back from the young Sun → the protoplanetary disk (volumetric
//   flared gas, 400k Keplerian dust grains, gaps carved by protoplanets) → planetesimal
//   collisions at their timeline screen positions → fly in to the proto-Earth → Theia →
//   giant impact → debris ring → the Moon coalesces → push in to the IV→V molten disc.
//   From 81 s the Earth's surface frame is chapter V's planet frame, so the crack networks of the
//   two chapters coincide through the IV→V dissolve (./ch4/vspin.js).
//
// World model and camera maths: ./ch4/geom.js. Camera keys: timeline cameras.IV, generated by
// ./ch4/camgen.mjs (the final hold is solved exactly for the IV→V contract).
import * as G from './ch4/geom.js';
import { Disk } from './ch4/disk.js';
import { Sun } from './ch4/sun.js';
import { DOF } from './ch4/dof.js';
import { Rocks } from './ch4/rocks.js';
import { Worlds } from './ch4/worlds.js';
import { Debris } from './ch4/debris.js';
import { loadVSpin } from './ch4/vspin.js';

const NEAR = 0.01, FAR = 1400;
let S = null;          // chapter state (built in init)

const { sstep } = G;
const lerp = (a, b, u) => a + (b - a) * u;
/** Piecewise smooth keys [[t, v], …] with smoothstep between them. */
function keyed(keys, t) {
  if (t <= keys[0][0]) return keys[0][1];
  for (let i = 0; i < keys.length - 1; i++) {
    if (t < keys[i + 1][0]) return lerp(keys[i][1], keys[i + 1][1], sstep(keys[i][0], keys[i + 1][0], t));
  }
  return keys[keys.length - 1][1];
}

// ---------------------------------------------------------------- timing curves (pure f(t))
const glareAt = (t) => Math.pow(1 - sstep(58.0, 60.0, t), 1.5);
const gasAt = (t) => keyed([[63.4, 1], [66.0, 0.45], [69.4, 0.32], [71.5, 0.1], [74.0, 0.0]], t);
const dustAt = (t) => keyed([[64.6, 1], [66.8, 0.4], [70.5, 0.22], [80.2, 0.0]], t);
const localDustAt = (t) => keyed([[63.2, 0], [66.0, 1], [76, 0.8], [80.2, 0]], t);
const apertureAt = (t) => keyed([[60.5, 0], [62.5, 2.0], [64.0, 5.5], [66.0, 7.0], [69.3, 7.0], [72, 6.0], [79.5, 5.0], [80.6, 0.0]], t);

export default {
  id: 'IV',

  async init(ctx) {
    const { THREE, T, W, H } = ctx;
    const depthTexture = new THREE.DepthTexture(W, H, THREE.FloatType);
    const sceneRT = new THREE.WebGLRenderTarget(W, H, {
      type: THREE.HalfFloatType, depthBuffer: true, stencilBuffer: false, depthTexture,
      minFilter: THREE.LinearFilter, magFilter: THREE.LinearFilter, generateMipmaps: false,
    });
    sceneRT.texture.colorSpace = THREE.NoColorSpace;
    const camera = new THREE.PerspectiveCamera(40, W / H, NEAR, FAR);
    const scene = new THREE.Scene();
    const fx = new THREE.Scene();                  // scatter-bokeh particles, drawn after DOF
    const disk = new Disk(); disk.init(ctx);
    const sun = new Sun(); sun.init(ctx);
    const dof = new DOF(); dof.init(ctx);
    const geom = G.impactGeom(T, W / H);
    const moon = G.moonPhase81(T, geom, W / H);
    const rocks = new Rocks(); rocks.init(ctx, geom);
    const worlds = new Worlds(); worlds.init(ctx, geom, moon, await loadVSpin());
    rocks.theiaPos = (t) => worlds.theiaPosAt(t);
    const debris = new Debris(); debris.init(ctx, geom, moon);
    scene.add(sun.stars, sun.sphere, sun.corona, ...rocks.sceneObjects(), ...worlds.sceneObjects(), ...debris.sceneObjects());
    fx.add(disk.dust, ...rocks.fxObjects(), ...worlds.fxObjects(), ...debris.fxObjects());
    const kicks = T.kicks.filter((k) => k > 50 && k < 90);
    S = { sceneRT, camera, scene, fx, disk, sun, dof, rocks, worlds, debris, geom, moon, kicks, theiaT: T.THEIA_T };
  },

  render(ctx, t, target) {
    const { THREE, T, renderer: r } = ctx;
    const { camera, scene, fx, disk, sun, dof, sceneRT } = S;
    ctx.applyCamera(camera, T.sampleCamera(T.cameras.IV, t));
    camera.near = NEAR; camera.far = FAR; camera.updateProjectionMatrix();
    const psi = G.psi(t);
    const feat = ctx.features.at(t);

    // kicks → stellar flares (corona) + light echoes through the disk + dust shimmer
    const echo = new THREE.Vector4(-1, -1, -1, -1);
    let flare = 0, nK = 0, lastK = -1;
    for (let i = S.kicks.length - 1; i >= 0 && nK < 4; i--) {
      const a = t - S.kicks[i];
      if (a < 0) continue;
      if (a < 3) echo.setComponent(nK, a);
      if (lastK < 0) lastK = i;
      flare += Math.exp(-a / 0.3) * (nK === 0 ? 1 : 0.6);
      nK++;
    }
    const flareAng = lastK >= 0 ? T.hash1(lastK * 7 + 3) * Math.PI * 2 : 0;
    const lastKick = lastK >= 0 ? t - S.kicks[lastK] : 9;
    const kickEnv = Math.exp(-lastKick / 0.16) * (lastKick < 2 ? 1 : 0);

    // ---- uniforms
    sun.u.uT.value = t; sun.u.uFlare.value = flare;
    sun.coronaU.uT.value = t; sun.coronaU.uSpike.value = sstep(12, 30, camera.position.length()); sun.coronaU.uFlare.value = flare + feat.high * 0.3; sun.coronaU.uFlareAng.value = flareAng;
    sun.starU.uCam.value.copy(camera.position);
    sun.starU.uAmt.value = 0.8 + 0.5 * sstep(78, 81, t);
    const focusD = this.focusAt(t, camera);
    const aperture = apertureAt(t);
    const P = { near: NEAR, far: FAR, focus: focusD, aperture, maxCoc: 90, t };

    const du = disk.dustU;
    du.uT.value = t; du.uPsi.value = psi; du.uDust.value = dustAt(t); du.uLum.value = 16 * 220 / 400;
    du.uShimmer.value = Math.min(1.5, flare * 0.8 + feat.high * 0.5); du.uLocal.value = localDustAt(t);
    du.uEcho.value.copy(echo);
    du.uFocus.value = focusD; du.uAperture.value = aperture; du.uDepth.value = sceneRT.depthTexture; du.uNear.value = NEAR; du.uFar.value = FAR;

    S.rocks.update(ctx, t, camera, P, sceneRT);
    S.worlds.update(ctx, t, camera, P, sceneRT);
    S.rocks.mat.uniforms.uEarthGlow.value = S.worlds.earthGlow;
    S.debris.fragMat.uniforms.uEarthGlow.value = S.worlds.earthGlow;
    S.debris.u.uEarthGlow.value = S.worlds.earthGlow;
    S.worlds.earthMat.uniforms.uEarthKick.value = t > T.THEIA_T ? (kickEnv + 0.4 * feat.low) * (1 - sstep(80.3, 81.0, t)) : 0;
    S.debris.u.uKick.value = t > T.THEIA_T ? kickEnv : 0;
    S.debris.update(ctx, t, camera, P, sceneRT);

    // ---- 1. surfaces → sceneRT (colour + depth texture)
    ctx.clear(sceneRT, [0, 0, 0]);
    r.autoClear = false;
    r.setRenderTarget(sceneRT);
    r.render(scene, camera);
    r.autoClear = true;

    // ---- 2. volumetric gas (depth-aware raymarch), composited with transmittance
    const gasAmt = gasAt(t);
    if (gasAmt > 0.001) {
      const gu = disk.gas.uniforms;
      gu.uInvProj.value.copy(camera.projectionMatrixInverse); gu.uCamWorld.value.copy(camera.matrixWorld);
      gu.uCamPos.value.copy(camera.position);
      disk.gas.render(r, disk.half, {
        uDepth: sceneRT.depthTexture, uNear: NEAR, uFar: FAR, uT: t, uPsi: psi, uGas: gasAmt, uLum: 2.9, uKappa: 0.85, uNearFade: sstep(63.0, 65.0, t),
        uSeed: (Math.round(t * 60) % 997) * 0.37, uFlare: flare, uEcho: echo,
      });
      r.autoClear = false;
      disk.comp.render(r, sceneRT);
      r.autoClear = true;
    }

    // ---- 3. DOF + glare → target
    const sp = new THREE.Vector3(0, 0, 0).project(camera);
    P.glare = glareAt(t);
    P.glareC = new THREE.Vector2(sp.x * 0.5 + 0.5, sp.y * 0.5 + 0.5);
    dof.run(ctx, sceneRT, target, P);

    // ---- 4. scatter-bokeh emitters on top
    r.autoClear = false;
    r.setRenderTarget(target);
    r.render(fx, camera);
    r.autoClear = true;
    r.setRenderTarget(null);
  },

  focusAt(t, camera) {
    const c = camera.position;
    const dSun = c.length();
    const e = S.worlds.earthPosAt(t);
    let dE = Math.hypot(c.x - e[0], c.y - e[1], c.z - e[2]) - G.RE * 0.6;
    // during Theia's approach, rack focus partway toward it (both bodies read)
    const th = S.worlds.theiaPosAt(t);
    const dT = Math.hypot(c.x - th[0], c.y - th[1], c.z - th[2]);
    dE = lerp(dE, dT, 0.45 * sstep(65.8, 66.6, t) * (1 - sstep(69.0, 69.5, t)));
    return Math.exp(lerp(Math.log(dSun), Math.log(Math.max(dE, 0.05)), sstep(63.0, 65.8, t)));
  },

  post(t) {
    const heavy = sstep(57.4, 59.5, t) * (1 - sstep(79.4, 81.0, t));
    const ti = S ? S.theiaT : 69.367;
    const imp = t >= ti ? Math.exp(-(t - ti) / 1.5) * 0.4 : 0;
    return {
      exposure: 1.0,
      bloom: lerp(0.55, 1.05, heavy) + 0.25 * imp,
      threshold: lerp(1.0, 0.9, heavy),
      knee: 0.65,
      bloomRadius: lerp(1.0, 1.2, heavy),
      vignette: lerp(0.33, 0.44, heavy),
      grain: lerp(0.03, 0.055, heavy),
      ca: lerp(0.0013, 0.0024, heavy),
      lift: 0.0,
      saturation: lerp(1.0, 1.06, heavy),
      tint: [lerp(1, 1.02, heavy), 1.0, lerp(1, 0.96, heavy)],
    };
  },
};
